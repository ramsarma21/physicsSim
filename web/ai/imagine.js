// Imagine-first for a new scene from words (ai/experiments/imagine; ai/research/round3-plan.md §1.1, §4.1): a multi-step chain first gets a
// concept picture of the setup from the server's imagine step (a catalog pre-pass, then the image model), which is observed and planned from
// with the words in charge. It informs the plan only: it is never treated as the user's picture (no reconcile or coverage, no observation or
// picture in any critic or rate payload, no "covers", no "unsure" lines, no plan differences about "the picture"). Any failure on this path
// falls back to the words alone with one info line. Pure helpers; ./orchestrator.js does the calls.
//   import { conceptRoute, CONCEPT_NOTE, CONCEPT_LABEL } from "./imagine.js"
//   const how = conceptRoute({ mode, images, text, imagine })   // null | "observe" | "direct"

// what the concept picture is called for the models, and the words sent with it (verbatim from integration/orchestrator-imagine.diff)
export const CONCEPT_LABEL = "concept image generated by the app from the request"
export const CONCEPT_NOTE =
	"(The attached picture is a concept image the app generated from these words to suggest a buildable layout; it is not the user's own picture. The words are the request: where the picture differs from them or would not work in the physics, follow the words and make it work, so every outcome they state really happens.)"
// Which new-scene requests get a concept picture first, and how it is used (ai/experiments/imagine, 2 samples × 40 requests, judged blind):
//  a multi-step chain (chain words, or 3+ action verbs; 11 of the 40 requests): concept -> observe -> plan ("observe"): hard pass 0.82 -> 0.95,
//    stated goals met 0.84 -> 0.97, judges +0.6 / +0.7, for +56 s p50 on a ~130 s build. ("direct", the plan reading the picture itself
//    without the observe step, got 0.91 / 0.94 / +0.9 / +0.9 for +13 s.)
//  any other new scene: no judged gain (−0.2 on both judges), +26..60 s: no concept unless the user asks for one ("always": "direct").
const CHAIN_RE = /\b(rube goldberg|chain reaction|contraption|machine|marble run|\d+[- ]?(stage|step)s?|stages|steps)\b/i
// (common science-class words that are not a chain: "a simple machine: a lever…", "a pulley machine", "a washing machine", "two steps of stairs")
const NOT_CHAIN_RE = /\b(simple|washing|vending|pulley) machines?\b|\bsteps? of (the )?stairs?\b/gi
const ACTION_RE = /\b(knock\w*|hit\w*|push\w*|roll\w*|fall\w*|drop\w*|launch\w*|fling\w*|flip\w*|bump\w*|slid\w*|swing\w*|tip\w*|crash\w*|smash\w*|land\w*|bounc\w*|shoot\w*|blow\w*|carr\w*|lift\w*|topple\w*|zigzag\w*|races?|flies|drives?)\b/gi
export const isChainRequest = (text) => {
	const t = String(text ?? "")
	return CHAIN_RE.test(t.replace(NOT_CHAIN_RE, " ")) || (t.match(ACTION_RE) ?? []).length >= 3
}
/** How a new scene from words uses a concept picture: null (none) | "observe" | "direct". mode: "off" (default) | "auto" | "always" |
 *  "observe" | "direct" (the setting "Concept sketch: Auto · Always · Off"; observe / direct force a route, for the bench). Off is the default:
 *  the ship rule of round3-plan §8 D failed for Auto on the live client (judges +0.13 against the +0.3 needed, p50 +81 s; partB/B/acceptance.md). */
export function conceptPlan(text, mode = "off") {
	if (mode === "off" || !String(text ?? "").trim()) return null
	if (mode === "observe" || mode === "direct") return mode
	const chain = isChainRequest(text)
	if (mode === "always") return chain ? "observe" : "direct"
	return chain ? "observe" : null
}

/** The setting's values (anything else, or nothing, is "off": the default, round3-plan §8 D). */
export const IMAGINE_MODES = ["auto", "always", "off", "observe", "direct"]
export const imagineMode = (v) => (IMAGINE_MODES.includes(v) ? v : "off")
/** The client's deadline on the imagine call (the server's own budget is 150 s): past it, the plan is made from the words alone. */
export const IMAGINE_DEADLINE_MS = 75000

/** When a build makes a concept: a NEW scene from words alone (never an edit or a check; a user photo always wins), per the setting. */
export function conceptRoute({ mode, images = [], text = "", imagine = "off" } = {}) {
	if (mode !== "new" || (Array.isArray(images) && images.length) || !String(text ?? "").trim()) return null
	return conceptPlan(text, imagineMode(imagine))
}

const isObj = (v) => v !== null && typeof v === "object" && !Array.isArray(v)
const num = (v) => (typeof v === "number" && Number.isFinite(v) ? v : null)
/** The imagine step's answer -> the concept ({image, mime, model, width, height, cast, story}) or null when it carries no picture. */
export function pickConcept(out) {
	const c = Array.isArray(out?.concepts) ? out.concepts.find((x) => isObj(x) && typeof x.data === "string" && /^data:image\/[a-z+.-]+;base64,/i.test(x.data)) : null
	if (!c) return null
	const cast = (Array.isArray(out.cast) ? out.cast : []).filter(isObj).map((x) => ({ type: String(x.type ?? ""), count: Number.isInteger(x.count) && x.count > 0 ? x.count : 1, ...(x.role ? { role: String(x.role) } : {}), ...(x.size ? { size: String(x.size) } : {}) })).filter((x) => x.type)
	const story = (Array.isArray(out.story) ? out.story : []).map((s) => String(s ?? "").trim()).filter(Boolean).slice(0, 6)
	return { image: c.data, mime: typeof c.mime === "string" ? c.mime : (/^data:(image\/[a-z+.-]+)/i.exec(c.data)?.[1] ?? "image/jpeg"), model: typeof c.model === "string" ? c.model : null, width: num(c.width) ?? 1536, height: num(c.height) ?? 1024, cast, story }
}

/** A plan's differences (and the like) that talk about "the picture / image / photo / concept": a concept is the app's own, never the user's,
 *  so they are left out of the card. */
const PICTURE_RE = /\b(the|this|that|your|its) (concept )?(picture|image|photo|photograph|concept|sketch|drawing)s?\b|\bconcept (picture|image|sketch)\b|\b(pictured|depicted|drawn|sketched)\b/i
export const mentionsPicture = (t) => PICTURE_RE.test(String(t ?? ""))
export const dropPictureLines = (list) => (Array.isArray(list) ? list : []).filter((t) => !mentionsPicture(t))
/** A text (the plan's own reply or notes on a concept build) without its sentences about "the picture / sketch / concept": "I left out the
 *  books, block and cup from the concept picture, because…" reads as if the person had given a picture. null when nothing is left. */
export function dropPictureSentences(text) {
	if (typeof text !== "string") return null
	const kept = text.split(/(?<=[.!?…])\s+/).filter((t) => t.trim() && !mentionsPicture(t))
	return kept.length ? kept.join(" ").trim() : null
}

/**
 * fn(signal) under a deadline: its own signal aborts at `ms` (or with the parent's). Past the deadline it throws {kind: "timeout"}; a parent
 * cancel throws the AbortError as it came.
 */
export async function withDeadline(fn, ms, parent = null) {
	const ctl = new AbortController()
	let late = false
	const onAbort = () => ctl.abort()
	if (parent?.aborted) ctl.abort()
	parent?.addEventListener?.("abort", onAbort, { once: true })
	let timer = 0
	const deadline = new Promise((_, reject) => {
		timer = setTimeout(() => {
			late = true
			ctl.abort()
			reject(Object.assign(new Error(`no answer within ${Math.round(ms / 1000)} s`), { kind: "timeout" }))
		}, ms)
	})
	try {
		return await Promise.race([fn(ctl.signal), deadline])
	} catch (e) {
		if (late && !parent?.aborted) throw Object.assign(new Error(`no answer within ${Math.round(ms / 1000)} s`), { kind: "timeout" })
		throw e
	} finally {
		clearTimeout(timer)
		parent?.removeEventListener?.("abort", onAbort)
	}
}
