// Writes the indexes that register the physics modules (one file per module in each place; see ai/../web/CONTRACT.md "Physics modules"):
//   machines/mod_<name>.py           the catalog (Python): found by machines/items.py itself (no index)
//   web/sim/modules/<name>.js        its exact port + the module's plug-ins (goal kinds, AI digest, knobs...) -> web/sim/modules/index.js
//   tooling/src/sim/modules/<name>.ts  its engine processes (optional)                                        -> tooling/src/sim/modules/index.ts
//   web/models/mod-<name>.js         its 3D models and view hooks (optional)                                   -> web/models/modules.js
// A module with catalog types has both the Python file and the web/sim port (the parity tools compare them).
//   node tools/gen-modules.mjs           write the indexes (only files whose text changes)
//   node tools/gen-modules.mjs --check   write nothing; exit 1 when an index is stale or a module is missing its other half
// After it, rebuild the engine bundle when the engine index changed (npm run build:engine) and GET /api/catalog?reload=1 on a server.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..")
const check = process.argv.includes("--check")
const list = (dir, re) => (existsSync(join(ROOT, dir)) ? readdirSync(join(ROOT, dir)).filter((f) => re.test(f)).sort() : [])

const py = list("machines", /^mod_[a-z0-9_]+\.py$/).map((f) => f.slice(4, -3))
const js = list("web/sim/modules", /^[a-z0-9_]+\.js$/).filter((f) => f !== "index.js").map((f) => f.slice(0, -3))
const ts = list("tooling/src/sim/modules", /^[a-z0-9_]+\.ts$/).filter((f) => f !== "index.ts").map((f) => f.slice(0, -3))
const view = list("web/models", /^mod-[a-z0-9_]+\.js$/).map((f) => f.slice(4, -3))

const problems = []
for (const n of py) if (!js.includes(n)) problems.push(`machines/mod_${n}.py has no port web/sim/modules/${n}.js`)
for (const n of js) if (!py.includes(n)) problems.push(`web/sim/modules/${n}.js has no machines/mod_${n}.py (every module's catalog is built by both)`)
const ident = (n) => `m_${n.replace(/[^a-z0-9_]/g, "_")}`

const simIndex = `// GENERATED by \`node tools/gen-modules.mjs\` from the files in this folder: do not edit (run it again after adding or removing one).
// Registers every physics module, in name order (machines/items.py imports machines/mod_<name>.py in the same order): its catalog types
// (register_all, as a catalog file's), its goal kinds for the summary (register_goal_kind) and its plug-ins (../plugins.js registerModule).
// A module file that fails to load or register is left out and said (console.warn; MODULE_ERRORS), as machines/items.py does: one module being
// written never stops the catalog. (Loaded with import() so a broken file cannot stop this one; registered in name order once all have settled.)
import { GoalCtx, TYPES, register_goal_kind, use_catalog_module } from "../items.js"
import { registerModule, setGoalCtx } from "../plugins.js"

// (PLAYGROUND_MODULES="a,b" loads only those, "" none: from node's environment, or globalThis.PLAYGROUND_MODULES set before this loads in a page)
const ONLY = typeof globalThis.process?.env?.PLAYGROUND_MODULES === "string" ? globalThis.process.env.PLAYGROUND_MODULES : typeof globalThis.PLAYGROUND_MODULES === "string" ? globalThis.PLAYGROUND_MODULES : null
const only = ONLY === null ? null : ONLY.split(",").map((s) => s.trim()).filter(Boolean)
const FILES = [${js.map((n) => `[${JSON.stringify(`mod_${n}`)}, () => import(${JSON.stringify(`./${n}.js`)})]`).join(", ")}].filter(([name]) => !only || only.includes(name.slice(4)))
/** The modules registered here (as machines/items.py MODULES names them), and why any could not be. */
export const MODULES = []
export const MODULE_ERRORS = {}
const loaded = await Promise.allSettled(FILES.map(([, load]) => load()))
FILES.forEach(([name], i) => {
	const r = loaded[i]
	try {
		if (r.status === "rejected") throw r.reason
		const m = r.value
		if (typeof m.register_all === "function") use_catalog_module(name, m.register_all)
		if (m.plugin) {
			const mod = registerModule({ ...m.plugin, name })
			for (const k of mod.goals) register_goal_kind(k.kind, (ctx, g) => k.summarize(ctx, g))
		}
		MODULES.push(name)
	} catch (e) {
		MODULE_ERRORS[name] = String(e?.stack ?? e).split("\\n").slice(0, 3).join(" | ")
		console.warn(\`web/sim: module \${name} could not be loaded and is left out: \${MODULE_ERRORS[name]}\`)
	}
})
// (the AI's goal checks, ai/goals.mjs and web/ai/goals.js, judge a module's goal on a run through this: a GoalCtx for {scene?, doc, track})
setGoalCtx((scene, doc, track) => {
	const items = new Map()
	if (scene && Array.isArray(scene.items)) {
		for (const i of scene.items) if (i && typeof i.id === "string") items.set(i.id, i)
	} else {
		for (const s of doc.solids) if (typeof s.item === "string" && !items.has(s.item)) items.set(s.item, { id: s.item, type: s.itemType })
	}
	const name = (iid) => (items.has(iid) ? (items.get(iid).name || TYPES[items.get(iid).type]?.name || iid) : iid)
	return new GoalCtx(scene ?? { items: [...items.values()], goals: [] }, doc, track, items, name)
})
`

const engineIndex = `// GENERATED by \`node tools/gen-modules.mjs\` from the files in this folder: do not edit (run it again after adding or removing one).
// Every module file's default export (a ProcessKind or a list of them) is registered with the engine (tooling/src/sim/plugins.ts).
// A module file that fails to load is left out and said (console.warn; ENGINE_MODULE_ERRORS): a document using its kinds is then refused with
// "no process kind", and every other document runs (the server's worker never stops for one module being written).
import { type ProcessKind, registerProcess } from "#sim/plugins.ts"

const FILES: readonly (readonly [string, () => Promise<{ default: unknown }>])[] = [${ts.map((n) => `[${JSON.stringify(n)}, () => import(${JSON.stringify(`#sim/modules/${n}.ts`)})]`).join(", ")}]
export const ENGINE_MODULES: string[] = []
export const ENGINE_MODULE_ERRORS: Record<string, string> = {}
const loaded = await Promise.allSettled(FILES.map(([, load]) => load()))
FILES.forEach(([name], i) => {
	const r = loaded[i]
	try {
		if (r === undefined || r.status === "rejected") throw r?.reason
		const kinds = r.value.default
		registerProcess(...((Array.isArray(kinds) ? kinds : [kinds]) as ProcessKind[]))
		ENGINE_MODULES.push(name)
	} catch (e) {
		ENGINE_MODULE_ERRORS[name] = String(e instanceof Error ? e.message : e)
		console.warn(\`engine: module \${name} could not be loaded and is left out: \${ENGINE_MODULE_ERRORS[name]}\`)
	}
})
`

const viewIndex = `// GENERATED by \`node tools/gen-modules.mjs\` from web/models/mod-*.js: do not edit (run it again after adding or removing one).
// The physics modules' model files: web/models3d.js loads them with its own groups (each exports register({addModel, addViewPlugin, kit, THREE})).
export const MODULE_GROUPS = [${view.map((n) => JSON.stringify(`mod-${n}`)).join(", ")}]
`

const outputs = [
	["web/sim/modules/index.js", simIndex],
	["tooling/src/sim/modules/index.ts", engineIndex],
	["web/models/modules.js", viewIndex]
]
let stale = 0
for (const [rel, text] of outputs) {
	const path = join(ROOT, rel)
	const old = existsSync(path) ? readFileSync(path, "utf8") : null
	if (old === text) continue
	stale++
	if (check) console.log(`stale: ${rel}`)
	else {
		writeFileSync(path, text)
		console.log(`wrote ${rel}`)
	}
}
for (const p of problems) console.log(`problem: ${p}`)
console.log(`modules: python [${py.join(", ")}], web/sim [${js.join(", ")}], engine [${ts.join(", ")}], view [${view.join(", ")}]`)
if (problems.length || (check && stale)) process.exit(1)
