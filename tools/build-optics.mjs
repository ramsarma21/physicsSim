// Writes web/sim/optics.js, the JavaScript of tooling/src/sim/optics.ts (the optics module's 2D ray tracer) for the 3D view and the AI's
// digest, which trace the same beams the engine traces: the file has no imports and uses only + − × ÷, Math.sqrt and its own sin, cos, exp
// and ln, so it gives the engine's bits in any JavaScript engine without the engine's math substitution. tools/build-engine.mjs runs this
// (npm run build:engine); alone:
//   node tools/build-optics.mjs           write it (only when its text changes)
//   node tools/build-optics.mjs --check   write nothing; exit 1 when web/sim/optics.js is not what tooling/src/sim/optics.ts makes
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { findEsbuild } from "./engine-math-transform.ts"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const src = path.join(root, "tooling", "src", "sim", "optics.ts")
const out = path.join(root, "web", "sim", "optics.js")
const esbuild = await findEsbuild()
if (!esbuild) {
	console.error("build-optics: esbuild is not installed (run `npm ci` in the project root).")
	process.exit(1)
}
const text = readFileSync(src, "utf8")
// (the deterministic-math promise: none of the functions the engine's build swaps, so the view needs no swap)
const banned = /\bMath\s*\.\s*(sin|cos|tan|atan2|atan|asin|acos|exp|expm1|log|log2|log10|log1p|hypot|pow|cbrt|random)\b|\*\*/
const code = text.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "")
const m = banned.exec(code)
if (m) {
	console.error(`build-optics: tooling/src/sim/optics.ts uses ${m[0]}: the tracer must use only + − × ÷, Math.sqrt and its own sin, cos, exp, ln`)
	process.exit(1)
}
const js = (await esbuild.transform(text, { loader: "ts", format: "esm", target: "es2022", legalComments: "inline" })).code
const header = "// GENERATED by tools/build-optics.mjs (npm run build:engine) from tooling/src/sim/optics.ts: do not edit.\n"
const body = header + js
const same = existsSync(out) && readFileSync(out, "utf8") === body
if (process.argv.includes("--check")) {
	if (!same) {
		console.error("build-optics: web/sim/optics.js is stale (run node tools/build-optics.mjs)")
		process.exit(1)
	}
	console.log("web/sim/optics.js is up to date")
} else {
	if (!same) writeFileSync(out, body)
	console.log(`web/sim/optics.js  ${(body.length / 1024).toFixed(1)} KiB${same ? " (unchanged)" : ""}`)
}
