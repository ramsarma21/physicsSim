// Writes tools/crpow-tables.ts, the constants of tools/crpow.ts (correctly rounded pow): log2 of the 256 reduction points of the logarithm,
// 2^(j/256) for j = 0..255, and the few double-double constants of its polynomials. Every number is computed here from first principles with
// BigInt arithmetic (tools/crpow-big.ts: atanh series for the logarithms, Taylor's series for the powers of two, then one exact rounding),
// so the file can be checked or remade anywhere:
//   node tools/gen-crpow-tables.mjs           write tools/crpow-tables.ts
//   node tools/gen-crpow-tables.mjs --check   exit 1 unless tools/crpow-tables.ts is exactly what this writes
import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { decompose, exp2DD, ln2Fixed, log2DD, roundRational } from "./crpow-big.ts"

const here = path.dirname(fileURLToPath(import.meta.url))
const out = path.join(here, "crpow-tables.ts")

const f64 = new Float64Array(1)
const u32 = new Uint32Array(f64.buffer)
const LE = new Uint8Array(new Uint32Array([1]).buffer)[0] === 1
const HI = LE ? 1 : 0
const LO = LE ? 0 : 1
const hex = (v) => ((f64[0] = v), u32[HI].toString(16).padStart(8, "0") + u32[LO].toString(16).padStart(8, "0"))
const fromWords = (hi, lo) => ((u32[HI] = hi >>> 0), (u32[LO] = lo >>> 0), f64[0])

/** [hi, lo]: the double-double nearest to num / den (num, den > 0 BigInt). */
const ddRational = (num, den) => {
	const hi = roundRational(num, den, 0)
	const [mh, he] = decompose(hi)
	// num / den - mh * 2^he = (num - mh * den * 2^he) / den
	let n
	let sh
	if (he >= 0) {
		n = num - ((mh * den) << BigInt(he))
		sh = 0
	} else {
		n = (num << BigInt(-he)) - mh * den
		sh = he
	}
	const lo = n === 0n ? 0 : n < 0n ? -roundRational(-n, den, sh) : roundRational(n, den, sh)
	return [hi, lo]
}

// ---- the logarithm's reduction: z in [2^-0.5, 2^0.5) (about) is cut into 256 intervals by the high word of its bits, from OFF up in steps
// of 4096; interval 149 holds 1 in its middle (2731 steps of the high word below 1, 1365 above: 2^-9.6 either way), so it needs no point
// of its own (c = 1). Every other interval i reduces z by invc = 1 / c, c its midpoint (exact: both ends have short mantissas).
const OFF = 0x3ff00000 - 2731 - 149 * 4096
const invcOf = (i) => {
	if (i === 149) return 1
	const a = fromWords(OFF + i * 4096, 0)
	const b = fromWords(OFF + (i + 1) * 4096, 0)
	return 1 / ((a + b) / 2)
}
const logTab = []
for (let i = 0; i < 256; i++) {
	const [h, l] = log2DD(invcOf(i)) // T = -log2(invc) = log2(c)
	logTab.push(hex(0 - h) + " " + hex(0 - l))
}
const expTab = []
for (let j = 0; j < 256; j++) {
	const [h, l] = exp2DD(j, 8)
	expTab.push(hex(h) + " " + hex(l))
}
// ln 2 and 1 / ln 2 from tools/crpow-big.ts's fixed point (2^-400 ulp): the remainder rounded twice is exact enough (2^-106 relative)
const W = 400
const L2 = ln2Fixed(W)
const ln2 = ddRational(L2, 1n << BigInt(W))
const invln2 = ddRational(1n << BigInt(W), L2)
const consts = {
	LN2: ln2,
	INVLN2: invln2,
	THIRD: ddRational(1n, 3n),
	FIFTH: ddRational(1n, 5n),
	SIXTH: ddRational(1n, 6n),
	R24: ddRational(1n, 24n)
}
const chunk = (rows, n) => {
	const lines = []
	for (let k = 0; k < rows.length; k += n) lines.push(`\t"${k ? " " : ""}${rows.slice(k, k + n).join(" ")}"`)
	return lines.join(" +\n")
}
const text = `// Generated by tools/gen-crpow-tables.mjs (BigInt arithmetic from first principles; \`node tools/gen-crpow-tables.mjs --check\` verifies it).
// The constants of tools/crpow.ts. Each number is 16 hex digits: the IEEE-754 bits of a double, high word first; a pair is a double-double.
// LOG2_TAB[i] = log2(c_i) as hi lo, c_i the midpoint of the logarithm's i-th interval (1 for i = 149): see tools/gen-crpow-tables.mjs.
// EXP2_TAB[j] = 2^(j/256) as hi lo.
export const OFF = 0x${OFF.toString(16)}
export const CONSTS = "${Object.entries(consts).map(([k, [h, l]]) => `${k}:${hex(h)}:${hex(l)}`).join(" ")}"
export const LOG2_TAB =
${chunk(logTab, 4)}
export const EXP2_TAB =
${chunk(expTab, 4)}
`
if (process.argv.includes("--check")) {
	const have = readFileSync(out, "utf8")
	if (have !== text) {
		console.error("tools/crpow-tables.ts differs from what tools/gen-crpow-tables.mjs computes")
		process.exit(1)
	}
	console.log("tools/crpow-tables.ts: up to date")
} else {
	writeFileSync(out, text)
	console.log(`wrote ${path.relative(process.cwd(), out)}: ${logTab.length} + ${expTab.length} entries`)
}
