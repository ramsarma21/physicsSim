"""Writes web/sim/trig.js: CPython's math.sin and math.cos of the arguments `degrees * (pi / 180)` for every multiple of 30 degrees up to +-3600.

Why: the builders turn an item's angle into radians (angle * D2R) and place parts with cos and sin of it, rounding to 5 decimals. At
multiples of 30 degrees those are 0, +-1/2, +-sqrt(3)/2, +-1, and an offset with five decimals lands exactly on a rounding tie, so
the last bit of sin/cos can flip the rounded number. JavaScript's Math.sin/cos (V8 fdlibm, JavaScriptCore and SpiderMonkey each differ) and
the C library CPython calls disagree in the last bit for a few percent of arguments, among them cos(+-120 deg). For these arguments the
module returns what CPython (macOS libm) returns, the same in every browser; any other argument uses Math.sin/Math.cos.
usage: python3 tools/parity/gen_trig.py
"""
import math
import os

PG = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D2R = math.pi / 180
RANGE = 3600
angles = list(range(-RANGE, RANGE + 1, 30))
sins = [math.sin(d * D2R) for d in angles]
coss = [math.cos(d * D2R) for d in angles]
out = os.path.join(PG, "web", "sim", "trig.js")
with open(out, "w") as f:
    f.write("// Generated by tools/parity/gen_trig.py: CPython's math.sin / math.cos of (degrees * pi / 180) for degrees = -3600, -3570 ... 3600.\n")
    f.write("// Do not edit; see the script for why. Index = degrees / 30 + 120.\n")
    f.write(f"export const TRIG30_RANGE = {RANGE}\n")
    for name, vals in (("TRIG30_SIN", sins), ("TRIG30_COS", coss)):
        f.write(f"export const {name} = [\n")
        for i in range(0, len(vals), 6):
            f.write("\t" + ", ".join(repr(v) for v in vals[i:i + 6]) + ("," if i + 6 < len(vals) else "") + "\n")
        f.write("]\n")
print(out, len(angles), "angles")
