"""Writes web/sim/sprites.js: the sprite records items.sprite_records() reads from scenes/*.json and the PNG files (sha256, size).

The browser has no files to read, so web/sim/items.js takes these records from the module this writes. Run it again if a sprite PNG or
scenes/three-balls.json / scenes/ball-drop.json changes (tools/parity/core.mjs fails with a "sprites" mismatch when it should be).
usage: python3 tools/parity/gen_sprites.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PG = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(PG, "machines"))
import items  # noqa: E402

NAMES = ["clay", "cord", "hand-holding", "hand-open", "hand-opening", "plastic", "rubber"]
recs = items.sprite_records(NAMES)
assert list(recs) == NAMES, list(recs)
out = os.path.join(PG, "web", "sim", "sprites.js")
with open(out, "w") as f:
    f.write("// Generated by tools/parity/gen_sprites.py: the records machines/items.py sprite_records() makes (file, sha256, size, scale).\n")
    f.write("// Do not edit; run the script again if a sprite PNG or scenes/three-balls.json or scenes/ball-drop.json changes.\n")
    f.write("export const SPRITE_RECORDS = " + json.dumps(recs, indent="\t", ensure_ascii=False) + "\n")
print(out)
